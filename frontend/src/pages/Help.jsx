import React from 'react';
import { Link } from 'react-router-dom';
import { Ban, BookOpen, Bot, Check, MessageCircleQuestion, ShieldCheck } from 'lucide-react';
import { vigilaiApi } from '../api/vigilai';
import { PageHeader } from '../components/PageHeader';
import { Notice } from '../components/States';
import { StatusBadge } from '../components/StatusBadge';
import { askVigilAI } from '../features/vigilai/VigilAIWidget';
import { DEFAULT_SUGGESTIONS } from '../features/vigilai/SuggestedQuestions';
import { useApi } from '../hooks/useApi';

const CAN = [
  'Explain monitoring, alerts, incidents, security rules SEC-001 to SEC-005 and remediation workflows',
  'Summarise your open incidents, findings and remediation requests using live platform data your role may see',
  'Suggest troubleshooting steps and point to the right page',
  'Explain roles, permissions, the architecture, APIs and configuration',
];
const CANNOT = [
  'Approve, reject or execute remediation',
  'Run scans or shell commands, or modify infrastructure and configuration',
  'Change incidents, users, roles or settings',
  'Reveal secrets such as API keys, tokens or passwords',
  'Answer questions unrelated to VigilOps (general knowledge, jokes, poems …)',
];
const SAFEGUARDS = [
  'Backend scope validation', 'Restricted knowledge retrieval', 'Authorised live-data functions', 'Role-aware access checks', 'Context minimisation',
  'Prompt-injection resistance', 'Response validation', 'Output sanitisation', 'Request rate limiting',
];
const WORKFLOWS = [
  {
    title: 'Application failure and recovery',
    steps: [
      ['Monitoring', '/monitoring', 'confirm the demo application is healthy'],
      ['Settings → Demo controls', '/settings', 'an Administrator injects a controlled outage'],
      ['Incidents', '/incidents', 'an incident opens from the Prometheus alert; request ACTION-001'],
      ['Remediation', '/remediation', 'an Administrator approves and executes; the worker recovers and verifies'],
      ['Audit Logs', '/audit', 'review the complete trail'],
    ],
  },
  {
    title: 'Security misconfiguration',
    steps: [
      ['Settings → Demo controls', '/settings', 'reset the sample configuration'],
      ['Security Findings', '/findings', 'run a scan and open the SEC-001 finding; request ACTION-002'],
      ['Remediation', '/remediation', 'an Administrator approves and executes; the worker corrects the file and re-scans'],
      ['Security Findings', '/findings', 'the finding is Resolved by the verification scan'],
      ['Audit Logs', '/audit', 'review the complete trail'],
    ],
  },
];

export default function Help() {
  const { data: status } = useApi(() => vigilaiApi.status(), []);
  const questions = status?.suggested_questions || DEFAULT_SUGGESTIONS;

  return (
    <>
      <PageHeader
        title="VigilAI / Help"
        subtitle="VigilAI is the built-in, read-only assistant for the VigilOps platform. It lives in the chat button at the bottom-right corner of every page."
        actions={
          <button type="button" className="btn-primary btn-sm" onClick={() => askVigilAI()}>
            <Bot size={14} aria-hidden="true" /> Open VigilAI
          </button>
        }
      />

      {status ? (
        <Notice tone={status.mode === 'ai' ? 'success' : 'neutral'} className="mb-4">
          <span className="flex flex-wrap items-center gap-2">
            <StatusBadge tone={status.enabled ? (status.mode === 'ai' ? 'success' : 'info') : 'neutral'} label={!status.enabled ? 'Disabled' : status.mode === 'ai' ? 'Live AI: Google Gemini' : 'Documentation mode'} />
            {!status.enabled
              ? 'VigilAI has been turned off by an Administrator.'
              : status.mode === 'ai'
              ? `Answers are generated by ${status.model} through the backend, grounded in the knowledge base and live platform data.`
              : status.provider === 'none'
              ? 'The AI provider is switched off on this server (AI_PROVIDER=none), so VigilAI answers directly from the knowledge base and live platform data.'
              : 'No Gemini API key is configured, so VigilAI answers directly from the knowledge base and live platform data without AI generation.'}
          </span>
        </Notice>
      ) : null}

      <div className="grid gap-4 lg:grid-cols-2">
        <section className="card">
          <div className="card-header">
            <h2 className="card-title flex items-center gap-2">
              <MessageCircleQuestion size={16} aria-hidden="true" /> Try asking
            </h2>
          </div>
          <ul className="divide-y divide-line">
            {questions.map((question) => (
              <li key={question}>
                <button type="button" className="flex w-full items-center justify-between gap-3 px-4 py-2.5 text-left text-sm text-content hover:bg-raised/60" onClick={() => askVigilAI(question)}>
                  {question}
                  <span className="text-xs font-medium text-brand">Ask</span>
                </button>
              </li>
            ))}
          </ul>
        </section>

        <section className="card">
          <div className="card-header">
            <h2 className="card-title">What VigilAI can and cannot do</h2>
          </div>
          <div className="grid gap-4 p-4 sm:grid-cols-2">
            <ul className="space-y-2">
              {CAN.map((item) => (
                <li key={item} className="flex items-start gap-2 text-sm text-content">
                  <Check size={15} className="mt-0.5 shrink-0 text-ok" aria-hidden="true" /> {item}
                </li>
              ))}
            </ul>
            <ul className="space-y-2">
              {CANNOT.map((item) => (
                <li key={item} className="flex items-start gap-2 text-sm text-content">
                  <Ban size={15} className="mt-0.5 shrink-0 text-danger" aria-hidden="true" /> {item}
                </li>
              ))}
            </ul>
          </div>
        </section>

        <section className="card">
          <div className="card-header">
            <h2 className="card-title flex items-center gap-2">
              <ShieldCheck size={16} aria-hidden="true" /> Safeguards
            </h2>
          </div>
          <div className="card-body">
            <p className="mb-3 text-sm text-muted">
              The restriction to VigilOps topics does not rely on the AI model following instructions. These checks run in the backend for every message:
            </p>
            <div className="flex flex-wrap gap-1.5">
              {SAFEGUARDS.map((item) => (
                <span key={item} className="tag">
                  {item}
                </span>
              ))}
            </div>
            <p className="mt-3 text-sm text-muted">
              The Gemini API key is stored only on the backend. If the provider is unavailable or its free quota is exhausted, VigilAI falls back to documentation answers and
              the rest of the platform keeps working.
            </p>
          </div>
        </section>

        <section className="card">
          <div className="card-header">
            <h2 className="card-title flex items-center gap-2">
              <BookOpen size={16} aria-hidden="true" /> Knowledge base topics
            </h2>
          </div>
          <div className="card-body flex flex-wrap gap-1.5">
            {(status?.knowledge_base_topics || []).map((topic) => (
              <span key={topic.document} className="tag" title={topic.document}>
                {topic.title}
              </span>
            ))}
            {!status ? <p className="text-sm text-muted">Loading…</p> : null}
          </div>
        </section>
      </div>

      <h2 className="section-title mt-8">Guided workflows</h2>
      <div className="grid gap-4 lg:grid-cols-2">
        {WORKFLOWS.map((workflow) => (
          <section key={workflow.title} className="card">
            <div className="card-header">
              <h3 className="card-title">{workflow.title}</h3>
            </div>
            <ol className="list-decimal space-y-2 py-4 pl-9 pr-4 text-sm text-content">
              {workflow.steps.map(([label, to, text], index) => (
                <li key={index}>
                  <Link to={to} className="font-medium text-brand hover:underline">
                    {label}
                  </Link>{' '}
                  — {text}
                </li>
              ))}
            </ol>
          </section>
        ))}
      </div>
    </>
  );
}
