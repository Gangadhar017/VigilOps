def _automation(action_code, reason) -> Dict[str, Any]:
    if action_code is None:
        return {"supported": False, "action_code": None, "action": None, "reason": reason}
    action = get_action(action_code)
    return {
        "supported": True,
        "action_code": action_code,
        "action": action.as_dict() if action else None,
        "reason": None,
    }


def incident_recommendation(incident: Incident) -> Dict[str, Any]:
    runbook = _ALERT_RUNBOOKS.get(incident.alert_name, _GENERIC_ALERT_RUNBOOK)
    action_code, reason = action_for_incident(incident)
    return {
        "problem": runbook["problem"],
        "affected_resource": incident.affected_resource,
        "evidence": {
            "alert": incident.alert_name,
            "description": incident.description,
            "occurrences": incident.occurrence_count,
            "alert_still_firing": incident.alert_active,
        },
        "possible_causes": runbook["possible_causes"],
        "recommended_steps": runbook["recommended_steps"],
        "troubleshooting": runbook["troubleshooting"],
        "automation": _automation(action_code, reason),
    }


def finding_recommendation(finding: SecurityFinding) -> Dict[str, Any]:
    rule = get_rule(finding.rule_id)
    action_code, reason = action_for_finding(finding)
    return {
        "problem": rule.description if rule else finding.rule_name,
        "affected_resource": f"{finding.resource_identifier} in {finding.target_file}",
        "evidence": finding.evidence,
        "detection_logic": rule.detection_logic if rule else None,
        "security_impact": rule.impact if rule else None,
        "recommendation": rule.recommendation if rule else finding.recommendation,
        "recommended_steps": _RULE_FIX_STEPS.get(finding.rule_id, []),
        "automation": _automation(action_code, reason),
    }


def alert_runbook(alert_name: str) -> Dict[str, Any]:
    return _ALERT_RUNBOOKS.get(alert_name, _GENERIC_ALERT_RUNBOOK)
