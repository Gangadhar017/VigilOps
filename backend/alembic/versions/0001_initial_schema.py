def _preserve_legacy_tables() -> None:
    bind = op.get_bind()
    if bind.dialect.name != "postgresql":
        return
    existing = set(sa.inspect(bind).get_table_names())
    if not any(marker in existing for marker in LEGACY_MARKERS):
        return
    op.execute(f'CREATE SCHEMA IF NOT EXISTS "{LEGACY_SCHEMA}"')
    for table in LEGACY_TABLES:
        if table in existing:
            # SET SCHEMA moves the table together with its indexes, constraints
            # and owned sequences: no data is copied or lost.
            op.execute(f'ALTER TABLE "{table}" SET SCHEMA "{LEGACY_SCHEMA}"')


